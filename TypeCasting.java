package geekForGeeks;

public class TypeCasting {
    public static void main(String[] args) {
        char ch = 'A';
        int x = ch;
        System.out.println(x);
        char piryanshu = 'a';
        int y = piryanshu;
        System.out.println(y);
        char harsh = '3';
        System.out.println((int)harsh);
    }
    
}
