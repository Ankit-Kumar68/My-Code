package geekForGeeks;

public class IncrementDecrement {
    public static void main(String[] args) {
        int ajay = 10;
        System.out.println(ajay);
        ajay = ajay + 6;
        System.out.println(ajay);
        ajay = ajay * 4;
        System.out.println(ajay);
        int x = 10;
        System.out.println(x++);
        System.out.println(x);
        


    }
    
}
